xor(1,0,1).
xor(1,1,0).

/*--------------------------------------------------------------
half_adder/4: half_adder(+/-,+/-,+/-)
--------------------------------------------------------------*/

half_adder(A,B,S,C):-
    xor(A,B,S),
    and(A,B,C).

/*--------------------------------------------------------------
full_adder/5: full_adder(+/-,+/-,+/-,+/-,+/-)

Note: Full adder is made of two half adders and an or-gate.
--------------------------------------------------------------*/


full_adder(A,B,Ci,S,Co):-
    xor(A,B,T1),
    xor(T1,Ci,S),
    and(T1,Ci,T2),
    and(A,B,T3),
    or(T3,T2,Co).

/*--------------------------------------------------------------
full_adder_3bit/5: All arguments +/-
--------------------------------------------------------------*/

full_adder_3bit(C0,number(A2,A1,A0),number(B2,B1,B0),number(S2, S1, S0),C3) :-
	full_adder(A0,B0,C0,S0,C1),
	full_adder(A1,B1,C1,S1,C2),
	full_adder(A2,B2,C2,S2,C3).


